/**
 * Validates integrity of canonical curriculum data:
 * - Unique IDs
 * - References resolving to existing units, competencies, and skills
 * - Valid prerequisite graphs
 */
export function validateCurriculumIntegrity(knownSkillIds?: Set<string>): {
  valid: boolean;
  errors: string[];
} {
  const errors: string[] = [];
  const compIdSet = new Set<string>();
  const unitIdSet = new Set<string>();

  // 1. Check unit uniqueness and validity
  for (const unit of CANONICAL_CURRICULUM_UNITS) {
    if (unitIdSet.has(unit.id)) {
      errors.push(`Duplicate unit ID: ${unit.id}`);
    }
    unitIdSet.add(unit.id);
  }

  // 2. Check competency uniqueness and references
  for (const comp of CANONICAL_CURRICULUM_COMPETENCIES) {
    if (compIdSet.has(comp.id)) {
      errors.push(`Duplicate competency ID: ${comp.id}`);
    }
    compIdSet.add(comp.id);

    if (!unitIdSet.has(comp.unitId)) {
      errors.push(`Competency ${comp.id} references non-existent unitId: ${comp.unitId}`);
    }

    if (knownSkillIds && !knownSkillIds.has(comp.skillId)) {
      errors.push(`Competency ${comp.id} references non-existent skillId: ${comp.skillId}`);
    }
  }

  // 3. Check unit's competencyIds array
  for (const unit of CANONICAL_CURRICULUM_UNITS) {
    for (const compId of unit.competencyIds) {
      if (!compIdSet.has(compId)) {
        errors.push(`Unit ${unit.id} references non-existent competencyId: ${compId}`);
      }
    }
    for (const prereqUnitId of unit.prerequisiteUnitIds) {
      if (!unitIdSet.has(prereqUnitId)) {
        errors.push(`Unit ${unit.id} references non-existent prerequisiteUnitId: ${prereqUnitId}`);
      }
    }
  }

  // 4. Check competency prerequisites and unlocks
  for (const comp of CANONICAL_CURRICULUM_COMPETENCIES) {
    for (const prereqId of comp.prerequisiteCompetencyIds) {
      if (!compIdSet.has(prereqId)) {
        errors.push(`Competency ${comp.id} references non-existent prerequisiteCompetencyId: ${prereqId}`);
      }
    }
    for (const unlockId of comp.unlocksCompetencyIds) {
      if (!compIdSet.has(unlockId)) {
        errors.push(`Competency ${comp.id} references non-existent unlocksCompetencyId: ${unlockId}`);
      }
    }
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}

